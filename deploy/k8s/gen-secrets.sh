# Generate the `tenancy-secrets` Secret with cryptographically random values.
#
# Idempotent: if the Secret already exists it is left untouched (rotating it
# would break the already-initialised PostgreSQL data directory).
#
#   sh deploy/k8s/gen-secrets.sh
#   kubectl -n tenancy-center get secret tenancy-secrets -o jsonpath='{.data}'
#
# The generated MCP API key is written to deploy/k8s/.generated-env (gitignored)
# so local verification can use it:
#   set -a; . deploy/k8s/.generated-env; set +a
#   pwsh scripts/verify.ps1 -BaseUrl http://localhost:30080 -McpApiKey "$MCP_API_KEY"
set -eu
export KUBECONFIG=${KUBECONFIG:-/etc/rancher/k3s/k3s.yaml}
HERE=$(cd "$(dirname "$0")" && pwd)
KUBECTL=${KUBECTL:-kubectl}

rand() {
  # alphanumeric only: safe for JDBC URLs, HTTP headers and shell interpolation
  head -c 256 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | cut -c1-"${1:-40}"
}

if "$KUBECTL" -n tenancy-center get secret tenancy-secrets >/dev/null 2>&1; then
  echo "tenancy-secrets already exists — keeping current values."
  echo "To rotate: delete the Secret and re-run this script, then restart workloads"
  echo "(note: PostgreSQL password rotation also requires ALTER USER)."
  exit 0
fi

"$KUBECTL" apply -f "$HERE/00-namespace.yaml" >/dev/null

POSTGRES_PASSWORD=$(rand 32)
MCP_DB_PASSWORD=$(rand 32)
JWT_SECRET=$(rand 64)
INTERNAL_TOKEN=$(rand 48)
MCP_API_KEY="mcp_$(rand 40)"
BOOTSTRAP_ADMIN_PASSWORD=$(rand 24)

"$KUBECTL" -n tenancy-center create secret generic tenancy-secrets \
  --from-literal=POSTGRES_USER=tenancy \
  --from-literal=POSTGRES_PASSWORD="$POSTGRES_PASSWORD" \
  --from-literal=MCP_DB_PASSWORD="$MCP_DB_PASSWORD" \
  --from-literal=TENANCY_SECURITY_JWT_SECRET="$JWT_SECRET" \
  --from-literal=TENANCY_INTERNAL_TOKEN="$INTERNAL_TOKEN" \
  --from-literal=TENANCY_SECURITY_API_KEYS="$MCP_API_KEY" \
  --from-literal=TENANCY_BOOTSTRAP_ADMIN_PASSWORD="$BOOTSTRAP_ADMIN_PASSWORD" \
  --dry-run=client -o yaml | "$KUBECTL" apply -f - >/dev/null

umask 077
cat > "$HERE/.generated-env" <<EOF
# Generated by gen-secrets.sh — gitignored, local verification only.
MCP_API_KEY=$MCP_API_KEY
BOOTSTRAP_ADMIN_PASSWORD=$BOOTSTRAP_ADMIN_PASSWORD
EOF

echo "tenancy-secrets created with random values."
echo "MCP API key (X-API-Key): $MCP_API_KEY"
echo "Saved to: $HERE/.generated-env (gitignored)"
